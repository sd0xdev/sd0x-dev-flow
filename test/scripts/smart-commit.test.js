  const fence = src.match(/`<PREFIX>` is:\n\n```bash\n([^\n]*)\n```/);
  assert.ok(fence, 'execute-mode.md must still define <PREFIX> in a fenced block');
  assert.equal(fence[1], CANONICAL_PREFIX,
    'and it must be the canonical prefix byte-for-byte — this copy is what the user pastes');

  // Rounds 87 and 88, Codex P2 twice. Two failed selectors first: `^ *<PREFIX>` could only ever
  // find lines that already complied, and indent-inside-a-fence was presentation — an
  // unindented fence, or a ```bash one, slipped straight past. Both times the test's NAME
  // claimed a completeness its selector could not deliver.
  //
  // So the document changed instead of the selector. § Recovery commands is now the one place a
  // paste-ready command may appear, and EVERY line of that block is checked — no selection step
  // remains to be wrong. What used to be a guess is now a property of the document.
  const section = src.slice(src.indexOf('## On a leak'));
  const block = section.match(/### Recovery commands[\s\S]*?```\n([\s\S]*?)```/);
  assert.ok(block, 'the § Recovery commands block must exist — it is where the contract lives');
  const cmds = block[1].split('\n').filter((l) => l.trim());
  assert.ok(cmds.length >= 3, `the block must still carry its commands; saw ${cmds.length}`);
  // Round 89, Codex P2: the label used to LEAD the line, which made the block's own "paste-ready"
  // claim false — `[amend]` is a command word, and `/bin/bash -c '[amend] true'` exits 127 with
  // "command not found", measured. It is a trailing comment now, so the line survives a paste.
  const defined = cmds.map((cmd) => {
    const m = cmd.match(/^<PREFIX> git -C '<REPO_ROOT>' \S.*?\s+# \[([a-z0-9-]+)\]$/);
    assert.ok(m, `every line of the recovery block must be a pinned command labelled by a trailing comment: ${cmd}`);
    return m[1];
  });
  assert.deepEqual(defined, [...new Set(defined)],
    `recovery labels must be unique — a duplicate makes "run [amend]" ambiguous: ${defined}`);

  // And the other half of the contract: no command may be spelled out anywhere ELSE in the
  // section. This is what makes "every line of that block" equal to "every recovery command" —
  // without it, the block could be complete and a bare `git show <sha>` could still sit in a
  // template, unpinned and exposed to an inherited GIT_DIR.
  //
  // FIVE selectors have failed here, each narrower than the claim above it. `^ *<PREFIX>` only
  // found lines that already complied. A line-start anchor missed a table cell (`| Inspect |
  // `git show <sha>` |`, which starts with `|`) and an `env -u GIT_DIR git show <sha>` line
  // (which starts with `env`). Keying on the OPERAND missed `git show HEAD`. Banning characters
  // across the whole span rejected prose for naming a variable while `$GIT status` walked
  // through. Classifying by token count admitted one-word `$GIT`, which executes whatever the
  // variable holds. Codex reproduced every one of them.
  //
  // The common shape: each tried to DECIDE whether a span was a command. So the sixth does not
  // decide — it enumerates. The copyable inventory is pinned exactly, and anything new fails
  // until an author adds it deliberately. There is no spelling left for a rule to miss, because
