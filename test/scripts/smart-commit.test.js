const guardPath = resolve(__dirname, '../../scripts/commit-msg-guard.sh');

// Helper: run guard script with a message, return { status, output }
function runGuard(message, env = {}) {
  const tmpDir = mkdtempSync(resolve(tmpdir(), 'smart-commit-test-'));
  const msgFile = resolve(tmpDir, 'COMMIT_MSG');
  writeFileSync(msgFile, message);
  try {
    const result = spawnSync('bash', [guardPath, msgFile], {
      encoding: 'utf8',
      env: { ...process.env, ...env },
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    return {
      status: result.status,
      output: (result.stdout || '') + (result.stderr || ''),
    };
  } finally {
    rmSync(tmpDir, { recursive: true, force: true });
  }
}

// Helper: the runtime validation documented in execute-mode.md.
// It deliberately does NOT re-implement the policy: the doc specifies running
// scripts/commit-msg-guard.sh itself, so this helper runs exactly that. A copy
// here would be the drift that P2-c of the round-40 review found — the tests
// would have been checking their own copy, not the shipped instruction.
function runValidateMsg(message, aiCoAuthor = false) {
  return runGuard(message, aiCoAuthor ? { ALLOW_AI_COAUTHOR: '1' } : {});
}

