// P1-e: a fixed EOF delimiter is injectable — a message line equal to it ends the heredoc
// and the remainder is read as shell. create-pr prohibits the same construct.
// The oracle E10 applies, named so E11 can apply the SAME function to a mutant rather
// than re-asserting the mutation it just made — which proves only that replace() works.
//
// The delimiter is read the way the shell reads it, not matched as one literal spelling. The
// oracle used to be `!code.includes("<<'EOF'")`, which is a single quoting form: `<<EOF`,
// `<<"EOF"` and `<<\EOF` all terminate on the very same `EOF` line and all passed a test named
// "no fixed-EOF heredoc" (Codex). Quoting the delimiter changes whether the BODY expands — it
// never changes what ends the document, so it cannot be what the check keys on.
// That alternation was still one spelling short of the shell, and quote removal is why. Bash
// strips quoting across the WHOLE delimiter word, component by component, so `<<E"OF"`,
// `<<'E'OF`, `<<\E\O\F` and `<<$'EOF'` all terminate on a plain `EOF` line — measured under bash
// 3.2.57, each running the line after the `EOF`, while the alternation reported `E`, `E`, `E`
// and nothing (Codex, round 94). `<<EOF'` is NOT one of them: an unterminated single quote is a
// syntax error there. It is kept below as a spelling to reject on FORM, not as an evasion that
// runs — an earlier version of this comment offered it as a correction to the fourth example,
// which was a misreading: the fourth example was `<<$'EOF'`, and that one does run.
// Matching one component of a word the shell reads as a whole cannot be made complete by adding
// components; there is always another way to split it.
//
// So the same inversion the executor's oracles took in round 89: these blocks may use ONE
// heredoc spelling, and the check first enforces the spelling and only then resolves it. A
// canonical opener is `<<'NAME'` or `<<-'NAME'` with an uppercase name — fully single-quoted,
// so no component is left for quote removal to rejoin. Everything else is rejected as a
// spelling, without needing to know what it would resolve to. `<<<` is a here-string, not a
// heredoc: it has no terminator line, so nothing in a message can close it.
// The lookahead is load-bearing, and its absence is the same bug one level up: without it
// `<<'E'OF` matches the prefix `<<'E'`, resolves to the harmless name `E`, and the trailing
// `OF` — which the shell rejoins into `EOF` — is simply not looked at. A canonical opener must
// consume the WHOLE delimiter word, so what follows the closing quote has to end it.
//
// `<` and `>` belong in that set: bash accepts a redirection directly against the delimiter, as
// in `cat <<'SAFE'>out`, and without them a legitimate canonical heredoc was rejected (Codex,
// round 95, confirmed running here).
const CANONICAL_HEREDOC = /^<<-?'([A-Z][A-Z0-9_]*)'(?=[\s;|&)<>]|$)/;

/**
 * Every `<<` in the block, as `{ ok, name }` — `ok:false` for anything that is not a canonical
 * opener.
 *
 * Every `<<`, not every heredoc OPERATOR, and that is a deliberate over-reach rather than an
 * oversight. Telling the two apart needs quote-, comment- and arithmetic-aware lexing: `printf
 * '%s\n' "<<EOF"`, a trailing `# … <<EOF`, and `(( mask = value << 2 ))` all contain the
 * characters and open nothing (Codex, round 95). Writing that lexer inside a documentation test
 * is how the executor's oracles ended up needing eleven rounds of repair.
 *
 * So the subset is stated instead of inferred: **a bash block in these documents may not contain
 * `<<` except as a canonical heredoc opener.** It fails closed, it costs nothing today — no such
 * construct exists in either file — and if one is ever needed the block gets restructured or the
 * rule gets a lexer, deliberately. What it must not do is fail closed *silently*, so the
 * assertion below names the policy rather than reporting a mystery.
 */
const heredocOpeners = (code) => {
  const found = [];
  // Whole-line comments still go first: a line that exists only to discuss the construct is the
  // one false alarm certain to happen, in the very files that document it.
  const live = liveCode(code);
  for (let i = live.indexOf('<<'); i >= 0; i = live.indexOf('<<', i + 2)) {
    if (live[i + 2] === '<') { i += 1; continue; }   // here-string
    const m = CANONICAL_HEREDOC.exec(live.slice(i));
    found.push(m ? { ok: true, name: m[1] } : { ok: false, name: live.slice(i, i + 24) });
  }
  return found;
};

const heredocOracle = (code) => heredocOpeners(code)
  .every((h) => h.ok && h.name !== 'EOF');

