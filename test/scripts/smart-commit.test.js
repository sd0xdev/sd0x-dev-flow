//   (a) A `#`-commented allocation satisfied both allocation oracles while the line that really
//       ran produced a fixed, predictable path — the exact property F3 exists to forbid, passing
//       because the evidence for it was in a comment.
//   (b) A line continuation splits `/bin/bash -p \` from `"$GUARD"`, so a site with no `--` was
//       not enumerated at all. It did not fail — it vanished, and `every()` over the remaining
//       sites stayed true. That is the round-75 finding again, one representation lower down.
