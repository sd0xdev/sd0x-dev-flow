// P2-c: the previous version of this file re-implemented the validator, so a divergence
// between execute-mode.md and the guard was undetectable. These assert the duplication
// is gone rather than that the two copies happen to agree.
// Scoped to fenced bash blocks on purpose: these documents DESCRIBE the constructs
// they forbid, so a whole-file scan flags the prose that explains the fix. That exact
// mistake (a structural test matching its own explanatory comment) is why this helper
// exists rather than a substring check over the raw file.
/**
 * Every fenced block, as `{ info, body }`, honouring CommonMark's run-length rule: a fence closes
 * only on a run at least as long as its opener. A four-backtick block holding a markdown example
 * is therefore one block, and its body is re-scanned, because the three-backtick fences inside it
 * are exactly what a reader copies.
 */
function fencedBlocks(text) {
  const lines = text.split('\n');
  const out = [];
  for (let i = 0; i < lines.length;) {
    // Round 97, Codex P2: the opener was anchored at column 0 and to backticks alone, while
    // CommonMark also accepts up to three spaces of indentation and a `~~~` delimiter. Both
    // render as code and both are copyable, so moving a fixed-`EOF` heredoc into ```` ```bash ````
    // indented by two spaces, or into `~~~bash`, handed E10/E12 an empty string to scan. The
    // helper's name claimed CommonMark coverage; only the recognizer was narrower.
    const open = /^( {0,3})(`{3,}|~{3,})(.*)$/.exec(lines[i]);
    // A backtick fence's info string may not itself contain a backtick (a tilde fence's may).
    if (!open || (open[2][0] === '`' && open[3].includes('`'))) { i++; continue; }
    const indent = open[1].length;
    const strip = new RegExp(`^ {0,${indent}}`);
    const body = [];
    for (i++; i < lines.length; i++) {
      const close = /^ {0,3}(`{3,}|~{3,})[ \t]*$/.exec(lines[i]);
      // Same delimiter CHARACTER as well as at least the same run length: `~~~` does not close a
      // ```` ``` ```` block, so a tilde run inside a backtick fence is content, not a terminator.
      if (close && close[1][0] === open[2][0] && close[1].length >= open[2].length) break;
      // A fenced block's content is de-indented by the opener's own indentation, so an indented
      // fence yields the same body text as an unindented one.
      body.push(lines[i].replace(strip, ''));
    }
    i++;
    const block = { info: open[3].trim(), body: body.join('\n') };
    out.push(block);
    if (!/^(bash|sh|shell)\b/.test(block.info)) out.push(...fencedBlocks(block.body));
  }
  return out;
}

/**
 * The bash a reader can copy out of `path`.
 *
 * Classified by the FIRST word of the info string, not by an exact match on it. `^```bash\n`
 * accepted only that spelling, so ```` ```bash title=manual ```` still rendered as a bash block
 * and still copied, while disappearing from every check built on this helper — Codex moved a
 * fixed-`EOF` heredoc into one in round 96 and E10 went right past it.
 *
 * Scoped to fenced blocks on purpose: these documents DESCRIBE the constructs they forbid, so a
 * whole-file scan flags the prose explaining the fix. That exact mistake — a structural test
 * matching its own explanatory comment — is why this helper exists rather than a substring check.
 */
function bashBlocks(path) {
  return fencedBlocks(readFileSync(path, 'utf8'))
    .filter((b) => /^(bash|sh|shell)\b/.test(b.info))
    .map((b) => b.body)
    .join('\n');
}

