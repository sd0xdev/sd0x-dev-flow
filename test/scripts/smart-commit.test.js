  assert.equal(heredocOracle(asBash(extended)), false, 'and its heredoc must be judged, not skipped');

  // Nesting, by CommonMark run length: a four-backtick markdown example is one block, and the
  // three-backtick bash fence inside it is what a reader actually copies — so it is scanned too.
  const nested = "````markdown\n```bash\ncat <<'EOF'\nmsg\nEOF\n```\n````\n";
  assert.equal(heredocOracle(asBash(nested)), false, 'a bash fence inside an example is still copyable');

  // Codex, round 97: the opener was anchored at column 0 and to backticks, so two more CommonMark
  // fence forms rendered as copyable bash while handing the oracle an empty string. SKILL.md
  // already ships two three-space-indented ```bash fences, which is how the indented case was
  // confirmed against the repository rather than assumed — before this, E10 had never read them.
  const indented = "   ```bash\n   cat <<'EOF'\n   msg\n   EOF\n   ```\n";
  assert.notEqual(asBash(indented), '', 'a fence indented up to three spaces is still a fence');
  assert.equal(heredocOracle(asBash(indented)), false, 'and its heredoc must be judged, not skipped');
  assert.equal(asBash(indented).includes('\n   '), false,
    'the body is de-indented by the opener, so an indented fence scans identically to a flush one');

  const tilde = "~~~bash\ncat <<'EOF'\nmsg\nEOF\n~~~\n";
  assert.notEqual(asBash(tilde), '', 'a ~~~ fence is a fence');
  assert.equal(heredocOracle(asBash(tilde)), false, 'and its heredoc must be judged too');

  // Delimiter TYPE, not just run length: `~~~` must not close a backtick fence, or the block ends
  // early and everything after the false terminator drops off the scanned surface.
  const crossed = "```bash\ncat <<'EOF'\n~~~\nmsg\nEOF\n```\n";
  assert.equal(heredocOracle(asBash(crossed)), false,
    'a tilde run inside a backtick fence is content — the heredoc after it must still be seen');

