const { test } = require('node:test');
const assert = require('node:assert/strict');
const { resolve } = require('node:path');
const { statSync, writeFileSync, mkdtempSync, rmSync } = require('node:fs');
const { spawnSync } = require('node:child_process');
const { tmpdir } = require('node:os');

const guardPath = resolve(__dirname, '../../scripts/commit-msg-guard.sh');

// Helper: run guard script with a message, return { status, output }
function runGuard(message, env = {}) {
  const tmpDir = mkdtempSync(resolve(tmpdir(), 'smart-commit-test-'));
  const msgFile = resolve(tmpDir, 'COMMIT_MSG');
  writeFileSync(msgFile, message);
  try {
    const result = spawnSync('bash', [guardPath, msgFile], {
      encoding: 'utf8',
      env: { ...process.env, ...env },
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    return {
      status: result.status,
      output: (result.stdout || '') + (result.stderr || ''),
    };
  } finally {
    rmSync(tmpDir, { recursive: true, force: true });
  }
}

// Helper: run validate_msg inline shell function
// NOTE: This intentionally duplicates the validate_msg logic from SKILL.md Step 5c.
// It tests the documented behavior spec, not a shared import. If the SKILL.md
// patterns change, these tests must be updated in sync.
function runValidateMsg(message, aiCoAuthor = false) {
  const tmpDir = mkdtempSync(resolve(tmpdir(), 'smart-commit-validate-'));
  const msgFile = resolve(tmpDir, 'MSG');
  writeFileSync(msgFile, message);
  const script = `
AI_CO_AUTHOR="${aiCoAuthor ? '1' : '0'}"

validate_msg() {
  local tmpfile="$1"
  if [ "$AI_CO_AUTHOR" = "1" ]; then
    grep -Eiv '^Co-Authored-By: Claude <noreply@anthropic\\.com>$' "$tmpfile" | \\
      grep -Ei 'Co-Authored-By:.*(Claude|Anthropic|GPT|OpenAI|Copilot|noreply@anthropic)' && return 1
  else
    grep -Ei 'Co-Authored-By:.*(Claude|Anthropic|GPT|OpenAI|Copilot|noreply@anthropic)' "$tmpfile" && return 1
  fi
  grep -Ei 'Generated (by|with).*(Claude|\\bAI\\b|GPT|OpenAI|Copilot)' "$tmpfile" && return 1
  grep -Ei '🤖.*(Claude|\\bAI\\b|GPT|OpenAI)' "$tmpfile" && return 1
  return 0
}

validate_msg "${msgFile}"
`;
  try {
    const result = spawnSync('bash', ['-c', script], {
      encoding: 'utf8',
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    return { status: result.status };
  } finally {
    rmSync(tmpDir, { recursive: true, force: true });
  }
}

