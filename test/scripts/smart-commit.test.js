test('D1: POSIX ERE alternation without backslash works', () => {
  // Verify the guard uses ERE (unescaped | for alternation)
  const r1 = runGuard('fix: something\n\nCo-Authored-By: GPT-4 <gpt@openai.com>');
  assert.notEqual(r1.status, 0, 'GPT alternation should match');

  const r2 = runGuard('fix: something\n\nCo-Authored-By: Copilot <copilot@github.com>');
  assert.notEqual(r2.status, 0, 'Copilot alternation should match');

  const r3 = runGuard('fix: something\n\nGenerated with AI tools');
  assert.notEqual(r3.status, 0, 'Generated with AI should match');
});

test('D2: POSIX ERE grouping without non-capturing syntax works', () => {
  // ERE uses (...) not (?:...) — verify patterns work correctly
  const r1 = runGuard('fix: something\n\nGenerated by Claude Code');
  assert.notEqual(r1.status, 0, 'Generated by should match');

  const r2 = runGuard('fix: something\n\nGenerated with GPT');
  assert.notEqual(r2.status, 0, 'Generated with should match');
});

